def get_terrain_info(spot_id):
    """Get terrain info for a spot."""
    return TERRAIN_DATA.get(spot_id, {})

def get_spots_with_terrain():
    """Get all spots with terrain data."""
    return TERRAIN_DATA

def search_by_terrain(seabed_type=None, difficulty=None, night=False):
    """Search spots by terrain characteristics."""
    results = []
    for spot_id, info in TERRAIN_DATA.items():
        if seabed_type and seabed_type not in info.get("seabed", ""):
            continue
        if difficulty:
            access = info.get("access", "")
            if difficulty == "easy" and "容易" not in access:
                continue
            elif difficulty == "medium" and "中等" not in access:
                continue
            elif difficulty == "hard" and "渡輪" not in access and "需" not in access:
                continue
        if night and not info.get("night_fishing", False):
            continue
        results.append({"id": spot_id, **info})
    return results

